/**
 * アプリ内表示用のプライバシーポリシー本文を返す。
 *
 * @param appName アプリ名
 * @param lastUpdated 最終更新日（表示用）
 * @param contactEmail お問い合わせ先メール
 */
fun buildPrivacyPolicyText(
    appName: String,
    lastUpdated: String,
    contactEmail: String,
): String {
    return """
        最終更新日: $lastUpdated

        本プライバシーポリシーは、$appName（以下「本アプリ」）における
        利用者情報の取扱いを説明するものです。

        1. 基本方針
        本アプリは、端末内で動画・字幕ファイルを読み込み、
        シャドーイング練習を支援するツールです。
        開発者は、利用者が選択した動画・字幕の内容を
        開発者のサーバーへ送信しません。

        2. 端末内で保存・処理する情報
        以下は利用者の端末内のみで保存・処理されます。
        ・選択した動画・字幕ファイルへの参照（URI）
        ・再生位置、字幕オフセット、再生速度、UI 設定
        ・作品ごとの練習設定（最大30件）

        3. 第三者サービス（広告・分析）
        本アプリは、以下の Google 提供サービスを利用します。
        各サービス提供者のポリシーもあわせてご確認ください。

        (1) Google AdMob（広告）
        画面上部に広告を表示します。
        広告配信のため、Google および広告パートナーが
        広告 ID、端末情報、IP アドレス、
        広告の表示・クリックに関する情報等を
        収集・利用する場合があります。
        詳細: https://policies.google.com/technologies/partner-sites

        (2) Firebase Crashlytics（クラッシュ解析）
        不具合改善のため、クラッシュ時のログ、
        端末モデル、OS バージョン、アプリバージョン等が
        Google へ送信される場合があります。

        4. 広告のパーソナライズ
        広告は、Google の設定および端末の広告設定に従い
        表示されます。広告のカスタマイズは、
        端末の「Google 広告」設定等から変更できます。

        5. 利用者による削除
        アプリデータの削除、またはアプリのアンインストールにより、
        端末内に保存された本アプリの設定は消去されます。
        第三者サービス上の情報については、
        各サービス提供者の手順に従ってください。

        6. 未成年者
        本アプリは、13 歳未満の方を対象としていません。
        13 歳未満の方の利用は想定していません。

        7. ポリシーの変更
        法令・サービス内容の変更に伴い、
        本ポリシーを改定する場合があります。
        重要な変更は、アプリ更新等で告知します。

        8. お問い合わせ
        本ポリシーに関するお問い合わせ:
        $contactEmail
    """.trimIndent().replace("\n        ", "\n")
}

